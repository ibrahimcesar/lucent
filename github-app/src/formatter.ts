import { LucentMetrics, FileMetric } from './lucent';

/**
 * Format metrics as a GitHub PR comment
 */
export function formatMetricsComment(metrics: LucentMetrics, sha: string): string {
  const { files, summary } = metrics;

  const lines: string[] = [
    '## 💎 Lucent Code Metrics Report',
    '',
    `> Analysis of commit \`${sha.substring(0, 7)}\``,
    '',
    '### 📊 Summary',
    '',
    '| Metric | Value |',
    '|--------|-------|',
    `| Files Analyzed | ${summary.totalFiles} |`,
    `| Total Lines | ${summary.totalLines.toLocaleString()} |`,
    `| Code Lines | ${summary.totalCodeLines.toLocaleString()} |`,
    `| Avg Cyclomatic Complexity | ${summary.avgCyclomaticComplexity.toFixed(1)} |`,
    `| Avg Cognitive Complexity | ${summary.avgCognitiveComplexity.toFixed(1)} |`,
    `| Avg Maintainability | ${summary.avgMaintainability.toFixed(1)} (${getMaintainabilityGrade(summary.avgMaintainability)}) |`,
    '',
  ];

  // Add issues section if there are problems
  if (summary.criticalIssues > 0 || summary.highComplexityFiles > 0 || summary.lowMaintainabilityFiles > 0) {
    lines.push('### ⚠️ Issues Found');
    lines.push('');

    if (summary.criticalIssues > 0) {
      lines.push(`- 🔴 **${summary.criticalIssues}** critical issue${summary.criticalIssues > 1 ? 's' : ''}`);
    }
    if (summary.highComplexityFiles > 0) {
      lines.push(`- 🟠 **${summary.highComplexityFiles}** file${summary.highComplexityFiles > 1 ? 's' : ''} with high complexity (>20)`);
    }
    if (summary.lowMaintainabilityFiles > 0) {
      lines.push(`- 🟡 **${summary.lowMaintainabilityFiles}** file${summary.lowMaintainabilityFiles > 1 ? 's' : ''} with low maintainability (<50)`);
    }
    lines.push('');
  }

  // Add problem files
  const problemFiles = files.filter(f =>
    f.cyclomaticComplexity > 20 ||
    f.maintainabilityIndex < 50 ||
    f.codeSmells.some(s => s.severity === 'critical')
  );

  if (problemFiles.length > 0) {
    lines.push('### 📁 Files Needing Attention');
    lines.push('');
    lines.push('<details>');
    lines.push('<summary>Click to expand</summary>');
    lines.push('');
    lines.push('| File | Complexity | Maintainability | Issues |');
    lines.push('|------|------------|-----------------|--------|');

    for (const file of problemFiles.slice(0, 10)) {
      const complexityIcon = getComplexityIcon(file.cyclomaticComplexity);
      const maintIcon = getMaintainabilityIcon(file.maintainabilityIndex);
      const issues = file.codeSmells.filter(s => s.severity === 'critical' || s.severity === 'high').length;
      const issuesText = issues > 0 ? `${issues} issue${issues > 1 ? 's' : ''}` : '-';

      lines.push(
        `| \`${truncatePath(file.path)}\` | ${complexityIcon} ${file.cyclomaticComplexity} | ${maintIcon} ${file.maintainabilityIndex.toFixed(0)} (${file.maintainabilityGrade}) | ${issuesText} |`
      );
    }

    if (problemFiles.length > 10) {
      lines.push(`| ... | | | _${problemFiles.length - 10} more files_ |`);
    }

    lines.push('');
    lines.push('</details>');
    lines.push('');
  }

  // Add code smells details
  const criticalSmells = files.flatMap(f =>
    f.codeSmells
      .filter(s => s.severity === 'critical')
      .map(s => ({ ...s, file: f.path }))
  );

  if (criticalSmells.length > 0) {
    lines.push('### 🚨 Critical Code Smells');
    lines.push('');

    for (const smell of criticalSmells.slice(0, 5)) {
      const location = smell.line ? `:${smell.line}` : '';
      lines.push(`- **${smell.name}** in \`${smell.file}${location}\``);
      if (smell.description) {
        lines.push(`  - ${smell.description}`);
      }
    }

    if (criticalSmells.length > 5) {
      lines.push(`- _...and ${criticalSmells.length - 5} more_`);
    }
    lines.push('');
  }

  // Footer
  lines.push('---');
  lines.push('');
  lines.push('_Generated by [Lucent](https://github.com/ibrahimcesar/lucent) 💎_');

  return lines.join('\n');
}

/**
 * Format output for GitHub check run
 */
export function formatCheckRunOutput(
  metrics: LucentMetrics,
  totalChangedFiles: number
): { title: string; summary: string; text?: string } {
  const { summary } = metrics;

  // Determine status emoji
  let statusEmoji = '✅';
  if (summary.criticalIssues > 0) statusEmoji = '❌';
  else if (summary.highComplexityFiles > 0 || summary.lowMaintainabilityFiles > 0) statusEmoji = '⚠️';
  else if (summary.warnings > 0) statusEmoji = '📝';

  const title = `${statusEmoji} ${summary.totalFiles} file${summary.totalFiles !== 1 ? 's' : ''} analyzed`;

  const summaryLines = [
    `## Code Metrics Summary`,
    '',
    `| Metric | Value |`,
    `|--------|-------|`,
    `| Files Analyzed | ${summary.totalFiles} of ${totalChangedFiles} changed |`,
    `| Avg Complexity | ${summary.avgCyclomaticComplexity.toFixed(1)} |`,
    `| Avg Maintainability | ${summary.avgMaintainability.toFixed(1)} (${getMaintainabilityGrade(summary.avgMaintainability)}) |`,
  ];

  if (summary.criticalIssues > 0) {
    summaryLines.push(`| Critical Issues | 🔴 ${summary.criticalIssues} |`);
  }
  if (summary.highComplexityFiles > 0) {
    summaryLines.push(`| High Complexity Files | 🟠 ${summary.highComplexityFiles} |`);
  }
  if (summary.lowMaintainabilityFiles > 0) {
    summaryLines.push(`| Low Maintainability | 🟡 ${summary.lowMaintainabilityFiles} |`);
  }

  // Detailed text for expandable section
  const textLines: string[] = [];

  if (metrics.files.length > 0) {
    textLines.push('## File Details');
    textLines.push('');
    textLines.push('| File | Lang | LOC | CC | MI | Grade |');
    textLines.push('|------|------|-----|----|----|-------|');

    for (const file of metrics.files.slice(0, 20)) {
      textLines.push(
        `| ${truncatePath(file.path)} | ${file.language} | ${file.codeLines} | ${file.cyclomaticComplexity} | ${file.maintainabilityIndex.toFixed(0)} | ${file.maintainabilityGrade} |`
      );
    }

    if (metrics.files.length > 20) {
      textLines.push(`| ... | | | | | _${metrics.files.length - 20} more_ |`);
    }
  }

  return {
    title,
    summary: summaryLines.join('\n'),
    text: textLines.length > 0 ? textLines.join('\n') : undefined,
  };
}

/**
 * Get maintainability grade from index
 */
function getMaintainabilityGrade(index: number): string {
  if (index >= 85) return 'A';
  if (index >= 65) return 'B';
  if (index >= 50) return 'C';
  if (index >= 25) return 'D';
  return 'F';
}

/**
 * Get complexity icon based on value
 */
function getComplexityIcon(complexity: number): string {
  if (complexity <= 10) return '🟢';
  if (complexity <= 20) return '🟡';
  if (complexity <= 30) return '🟠';
  return '🔴';
}

/**
 * Get maintainability icon based on index
 */
function getMaintainabilityIcon(index: number): string {
  if (index >= 85) return '🟢';
  if (index >= 65) return '🟡';
  if (index >= 50) return '🟠';
  return '🔴';
}

/**
 * Truncate file path for display
 */
function truncatePath(path: string, maxLength: number = 40): string {
  if (path.length <= maxLength) return path;

  const parts = path.split('/');
  if (parts.length <= 2) {
    return '...' + path.slice(-(maxLength - 3));
  }

  // Keep first and last parts
  const first = parts[0];
  const last = parts.slice(-2).join('/');

  if (first.length + last.length + 5 <= maxLength) {
    return `${first}/.../${last}`;
  }

  return '...' + path.slice(-(maxLength - 3));
}
